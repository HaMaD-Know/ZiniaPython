const ICONS = {
  activity: Activity, arrowDown: ArrowDown, arrowLeft: ArrowLeft, arrowRight: ArrowRight, arrowUp: ArrowUp,
  braces: Braces, check: Check, chevronDown: ChevronDown, chevronRight: ChevronRight, chevronUp: ChevronUp,
  alert: CircleAlert, ok: CircleCheck, stopCircle: CircleStop, error: CircleX, paste: ClipboardPaste, cloud: Cloud,
  copy: Copy, duplicate: CopyPlus, enter: CornerDownLeft, download: Download, more: Ellipsis, clear: Eraser,
  file: File, fileCode: FileCode, fileImport: FileInput, newFile: FilePlus, fileText: FileText, folder: Folder,
  folderImport: FolderInput, folderOpen: FolderOpen, newFolder: FolderPlus, hash: Hash, device: HardDrive,
  history: History, dedent: IndentDecrease, indent: IndentIncrease, info: Info, keyboard: Keyboard,
  tree: ListTree, spinner: LoaderCircle, expand: Maximize2, menu: Menu, collapse: Minimize2, moon: Moon,
  package: Package, sidebar: PanelLeft, rename: Pencil, play: Play, plus: Plus, redo: Redo2, replace: Replace,
  restart: RotateCcw, save: Save, log: ScrollText, search: Search, settings: Settings, share: Share,
  stop: Square, terminal: SquareTerminal, sun: Sun, trash: Trash2, warning: TriangleAlert, undo: Undo2,
  upload: Upload, wrap: WrapText, close: X,
  cube: Box, shapes: Shapes, recenter: Scan, zoomIn: ZoomIn, zoomOut: ZoomOut,
} satisfies Record<string, IconNode>;

export type IconName = keyof typeof ICONS;

export function icon(name: IconName, size = 18, className = ''): SVGElement {
  const svg = createElement(ICONS[name], {
    width: size,
    height: size,
    'stroke-width': 1.9,
    'aria-hidden': 'true',
    class: `icon ${className}`.trim(),
  });
  return svg;
}
