"""Creates release/ZiniaPython-IDE-source.zip with everything needed to build.

    python scripts/package-release.py

Excluded: node_modules, build output, the downloaded CPython framework and
archive (fetched with checksum verification by the build), development-bridge
data, caches and any signing material.
"""

import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "release")
OUT = os.path.join(OUT_DIR, "ZiniaPython-IDE-source.zip")

EXCLUDED_DIRS = {
    "node_modules", "dist", "release", "coverage", ".git", "__pycache__", ".pytest_cache",
    ".dev-workspace", ".dev-runtime", "downloads", "Python.xcframework", "DerivedData", "build",
    ".claude",
    "public",  # ios/App/App/public is generated by `cap sync`; the root has its own public/ (kept below)
}
KEEP_DIRS = {os.path.join(ROOT, "public")}
EXCLUDED_FILES = {"capacitor.config.json", "config.xml", ".DS_Store", "Thumbs.db"}
EXCLUDED_SUFFIXES = (".pyc", ".p12", ".mobileprovision", ".cer", ".p8", ".ipa", ".xcarchive", ".log")


def included(path: str) -> bool:
    rel = os.path.relpath(path, ROOT)
    if rel.startswith(os.path.join("ios", "App", "App") + os.sep) and os.path.basename(path) in EXCLUDED_FILES:
        return False
    if os.path.basename(path) in {".DS_Store", "Thumbs.db"}:
        return False
    return not path.endswith(EXCLUDED_SUFFIXES)


def main() -> int:
    os.makedirs(OUT_DIR, exist_ok=True)
    count = 0
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for current, dirs, files in os.walk(ROOT):
            dirs[:] = sorted(d for d in dirs if d not in EXCLUDED_DIRS or os.path.join(current, d) in KEEP_DIRS)
            if os.path.basename(current) == "settings.local.json":
                continue
            for name in sorted(files):
                path = os.path.join(current, name)
                if not included(path) or name == "settings.local.json":
                    continue
                arcname = os.path.join("ZiniaPython-IDE", os.path.relpath(path, ROOT)).replace(os.sep, "/")
                zf.write(path, arcname)
                count += 1
    size = os.path.getsize(OUT) / (1024 * 1024)
    print(f"Wrote {OUT} ({count} files, {size:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
